  await page.getByRole('button', { name: '新建 EDM' }).click()
  await expect(page.getByRole('button', { name: '配色套餐 FunnyFuzzy 经典' })).toHaveCount(0)
  await page.getByRole('button', { name: '配色', exact: true }).click()
