import { test, expect } from '@playwright/test'

test('创建、编辑、保存并恢复 EDM 草稿', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建 EDM' }).click()
  await page.getByLabel('搜索楼层模板').fill('标题')
  await expect(page.getByRole('button', { name: '添加 标题居中' })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加 双列商品卡' })).toHaveCount(0)
  await page.getByRole('button', { name: '添加 标题居中' }).click()
  await page.getByRole('button', { name: '缩小画布' }).click()
  await expect(page.getByRole('status')).toHaveText('80%')
  await page.getByLabel('标题文案').fill('SUMMER PICKS')
  await expect(page.getByRole('heading', { name: 'SUMMER PICKS' })).toBeVisible()
  const floorFont = await page.locator('.floor-render').first().evaluate(element => getComputedStyle(element).fontFamily)
  const toolbarFont = await page.locator('.editor-toolbar').evaluate(element => getComputedStyle(element).fontFamily)
  expect(floorFont).toContain('Euclid Circular A')
  expect(toolbarFont).not.toContain('Euclid Circular A')
  const weightsReady = await page.evaluate(async () => {
    await document.fonts.ready
    return [300, 400, 500, 600, 700].map(weight => document.fonts.check(`${weight} 16px "Euclid Circular A"`))
  })
  expect(weightsReady).toEqual([true, true, true, true, true])
  await page.waitForTimeout(650)
  await page.getByRole('button', { name: '返回草稿', exact: true }).click()
  await expect(page.getByText('未命名 EDM')).toBeVisible()
  await page.getByRole('button', { name: '打开 未命名 EDM' }).click()
  await expect(page.getByRole('heading', { name: 'SUMMER PICKS' })).toBeVisible()
  await page.getByRole('button', { name: '完整预览' }).click()
  await expect(page.getByRole('dialog', { name: '完整预览' })).toBeVisible()
})

test('HEAD Logo 跟随主题色位并允许手动覆盖', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建 EDM' }).click()
  await expect(page.getByRole('button', { name: '配色套餐 FunnyFuzzy 经典' })).toHaveCount(0)
  await page.getByRole('button', { name: '配色', exact: true }).click()
  await expect(page.getByText('FunnyFuzzy 经典')).toBeVisible()
  await expect(page.getByText('主题色位 A')).toBeVisible()
  await page.getByRole('button', { name: '楼层', exact: true }).click()
  await page.getByRole('button', { name: '添加 品牌 Logo' }).click()

  const head = page.getByTestId('head-brand-logo')
  await expect(head).toBeVisible()
  await expect(page.locator('.theme-binding-status')).toHaveText('主题色位 A')
  await expect(head).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(head.locator('img')).toHaveCSS('width', '90px')
  await expect(head.locator('img')).toHaveCSS('height', '30px')

  await page.getByRole('button', { name: '白色', exact: true }).click()
  await expect(head.locator('img')).toHaveCSS('filter', 'invert(1)')
  await page.getByLabel('背景颜色色值').fill('#EFEFEF')
  await expect(page.locator('.theme-binding-status')).toHaveText('自定义颜色')
  await expect(head).toHaveCSS('background-color', 'rgb(239, 239, 239)')
  await page.getByRole('button', { name: '重新关联主题色位 A' }).click()
  await expect(page.locator('.theme-binding-status')).toHaveText('主题色位 A')
  await expect(head).toHaveCSS('background-color', 'rgb(255, 255, 255)')

  await page.getByRole('button', { name: '完整预览' }).click()
  const previewHead = page.getByRole('dialog', { name: '完整预览' }).getByTestId('head-brand-logo')
  await expect(previewHead).toHaveCSS('background-color', 'rgb(255, 255, 255)')
})

